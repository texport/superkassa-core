package io.github.texport.superkassa.offlinequeue.api.model

/**
 * Статус выполнения элемента очереди.
 */
enum class QueueStatus {
    /**
     * Команда создана и ожидает первой попытки обработки.
     */
    PENDING,

    /**
     * Команда находится в процессе выполнения (вызван обработчик).
     */
    IN_PROGRESS,

    /**
     * Команда успешно обработана и отправлена в ОФД.
     */
    SENT,

    /**
     * Попытка выполнения завершилась ошибкой, планируется повтор.
     */
    FAILED,

    /**
     * Команда отвергнута окончательно и к отправке больше не берётся.
     *
     * Отличается от [FAILED] тем, что повтора не будет: ни по расписанию,
     * ни по кнопке «повторить неудачные». Разбирать такую команду человеку.
     */
    REJECTED
}
