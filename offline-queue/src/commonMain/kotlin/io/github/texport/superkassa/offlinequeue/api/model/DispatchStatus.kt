package io.github.texport.superkassa.offlinequeue.api.model

/**
 * Результат попытки выполнения команды очереди, видимый для обработчика (handler).
 */
enum class DispatchStatus {
    /**
     * Команда успешно выполнена и должна быть помечена как отправленная.
     */
    SENT,

    /**
     * Выполнение команды завершилось сбоем; планируется повторная попытка в соответствии с политикой очереди.
     */
    FAILED
}
