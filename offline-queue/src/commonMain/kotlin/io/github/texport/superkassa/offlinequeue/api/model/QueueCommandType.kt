package io.github.texport.superkassa.offlinequeue.api.model

/**
 * Тип команды, которая будет отправляться в ОФД.
 */
enum class QueueCommandType {
    /**
     * Фискальный чек (продажа, покупка, возврат и т.д.).
     */
    TICKET,

    /**
     * Сменный отчет без гашения (X-отчет).
     */
    REPORT_X,

    /**
     * Сменный отчет с гашением (Z-отчет).
     */
    REPORT_Z,

    /**
     * Закрытие смены.
     */
    CLOSE_SHIFT,

    /**
     * Операции внесения или изъятия наличных.
     */
    MONEY_PLACEMENT,

    /**
     * Информационная команда (запрос состояния, пинг и т.д.).
     */
    INFO,

    /**
     * Служебная системная команда.
     */
    SYSTEM
}
