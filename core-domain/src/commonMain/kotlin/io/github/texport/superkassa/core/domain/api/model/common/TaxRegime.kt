package io.github.texport.superkassa.core.domain.api.model.common

import kotlinx.serialization.Serializable

/**
 * Режимы налогообложения кассового ядра (ККМ).
 */
@Serializable
enum class TaxRegime {
    /** Неплательщик НДС. */
    NO_VAT,

    /**
     * Плательщик НДС.
     *
     * Позиция облагается своей ставкой, а без неё — ставкой кассы: так
     * позиция уходит в БФД, так же её считают чек и счётчики смены.
     * Товар без НДС у плательщика — обычный случай.
     */
    VAT_PAYER,

    /**
     * Смешанный режим налогообложения.
     *
     * Налог считается так же, как у плательщика; отличие в чеке — ставка
     * печатается у каждой позиции.
     */
    MIXED
}
