package io.github.texport.superkassa.core.domain.api.model.shift

/**
 * Смена против предела в сутки на момент вопроса.
 *
 * Считается одним правилом и одними часами кассы — теми же, по которым
 * касса отказывает в продаже. Экран берёт отсюда, а не считает сам.
 *
 * @property deadlineAt момент, после которого касса перестаёт оформлять
 *   продажу, возврат, внесение и изъятие: сутки от первого платёжного
 *   документа смены. `null` — платёжных документов в смене ещё нет,
 *   и отсчёт не начат.
 * @property exceeded предел пройден: операции получат отказ, пока смену не закроют.
 */
data class ShiftDayLimitState(
    val deadlineAt: Long?,
    val exceeded: Boolean
)
