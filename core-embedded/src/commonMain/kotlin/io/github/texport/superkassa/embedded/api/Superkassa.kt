package io.github.texport.superkassa.embedded.api

import io.github.texport.superkassa.core.presentation.api.DeliveryApi
import io.github.texport.superkassa.core.presentation.api.OfflineQueueApi
import io.github.texport.superkassa.core.presentation.api.PrintApi
import io.github.texport.superkassa.core.presentation.api.SettingsApi
import io.github.texport.superkassa.core.presentation.api.SuperkassaApi

/**
 * Касса, работающая в процессе приложения.
 *
 * Одна касса владеет одним каталогом данных: второй экземпляр на том же
 * каталоге не создаётся, пока первый не закрыт. Все вызовы фасадов
 * блокирующие — из главного потока приложения их не делают.
 *
 * Пока касса открыта, она сама досылает автономную очередь в ОФД,
 * доставляет чеки покупателям и закрывает смену до предела в сутки,
 * если у кассы включено автозакрытие.
 */
interface Superkassa : AutoCloseable {
    /** Кассовые и фискальные операции. */
    val api: SuperkassaApi

    /**
     * Печатные формы: HTML, PDF, PNG — по виду и идентификатору, по одному
     * идентификатору документа и по пакету протокола. Тот же объект, что [api].
     */
    val print: PrintApi

    /** Настройки ядра: чтение и правка по правилам ядра. */
    val settings: SettingsApi

    /** Автономная очередь документов. */
    val queue: OfflineQueueApi

    /**
     * Доставка чека покупателю: состояние по каналам для журнала и повтор вручную.
     * Доставка идёт в фоне — ответ кассиру её не ждёт.
     */
    val delivery: DeliveryApi

    /** Печать на принтер системы. */
    val printer: DocumentPrinter

    /**
     * Досылает автономную очередь одним заходом, не дожидаясь паузы, —
     * под тем же замком писателя, что и чеки.
     *
     * Для фоновой работы платформы, которая будит приложение без экрана:
     * отправка мимо этого замка шла бы параллельно с новым чеком кассира.
     * Возвращает число отправленных документов.
     */
    fun sendQueueNow(): Int

    /**
     * Досылает чеки покупателям одним заходом, не дожидаясь паузы: всё,
     * чей срок наступил, включая оставшееся от прошлого запуска.
     *
     * Для фоновой работы платформы. Задачу, за которую одновременно
     * взялся фон, второй раз не отправляет. Возвращает число отправленных
     * задач — с успехом или отказом.
     */
    fun sendDeliveriesNow(): Int

    /**
     * Проверяет автозакрытие смены одним заходом, не дожидаясь паузы.
     * Для фоновой работы платформы. Возвращает число закрытых смен.
     */
    fun closeDueShiftsNow(): Int

    /** Останавливает досылку очереди, доставку чеков и автозакрытие, закрывает базу и освобождает каталог. */
    override fun close()
}
