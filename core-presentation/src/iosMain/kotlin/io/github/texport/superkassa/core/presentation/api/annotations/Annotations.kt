/**
 * iOS-реализация интерфейса-маркера [Payload].
 *
 * ### Обоснование дизайна:
 * Поскольку Jakarta Bean Validation является чисто JVM-технологией и отсутствует в Apple Native,
 * на iOS данный интерфейс компилируется в обычный локальный маркерный интерфейс. Это позволяет
 * классам-наследникам [Payload] (таким как кастомные уровни ошибок, объявленные в `commonMain`)
 * успешно компилироваться и на iOS.
 *
 * ### Что необходимо сделать в iOS-приложении:
 * Автоматический парсинг аннотаций Jakarta на iOS не выполняется. Если клиенту на iOS необходимо
 * локально обрабатывать метаданные валидации (payload):
 * 1. Либо вручную проверять объекты перед вызовом API, считывая типы через Kotlin-рефлексию.
 * 2. Либо использовать кроссплатформенный валидатор (например, Konform) в общем коде, транслирующий
 *    результаты проверок в UI.
